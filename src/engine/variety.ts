/**
 * Variety: no puzzle shown twice.
 *
 * A Cartridge draws puzzle i of a round from `seed + i`, which keeps a round
 * replayable but says nothing about puzzle 3 matching puzzle 1; with a pool
 * of a dozen puzzles (bonds to 5) a repeat inside five is likely. `distinct`
 * keeps the first draw when its key is new and otherwise walks on to further
 * seeds until one is, so a round, or a whole Math Wiz session that passes the
 * keys it has already shown, never asks the same question twice while the
 * pool has anything left.
 */
import { mulberry32, type Rng } from './rng'

/** Seeds stepped by a prime so the retry sequence never lands on another index's first draw inside one round. */
const STRIDE = 7919

/**
 * Puzzle `index` of the round seeded by `seed`, generated by `gen`, whose
 * `key` is not in `used`. After `tries` draws the last one is returned
 * anyway: a pool smaller than the round still has to serve something.
 */
export function distinct<T>(seed: number, index: number, used: ReadonlySet<string>, gen: (rng: Rng) => T, key: (puzzle: T) => string, tries = 24): T {
  let last: T | undefined
  for (let k = 0; k < tries; k++) {
    const p = gen(mulberry32(seed + index + k * STRIDE))
    if (!used.has(key(p))) return p
    last = p
  }
  return last as T
}
